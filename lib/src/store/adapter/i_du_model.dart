/// Example
///
/// ```dart
/// class User extends IDuModel {
///   final String name;
///   final int age;
///   User({required this.name, required this.age});
///
///   Map<String, dynamic> toMap() {
///     return <String, dynamic>{'name': name, 'age': age};
///   }
///
///   factory User.fromMap(Map<String, dynamic> map) {
///     return User(name: map['name'] as String, age: map['age'] as int);
///   }
///
///   @override
///   String toString() => 'User(name: $name, age: $age)';
/// }
///
/// class UserAdapter extends IDuBinaryMetaAdapter<User> {
///   @override
///   User fromMap(Map<String, dynamic> map) {
///     return User.fromMap(map);
///   }
///
///   @override
///   Map<String, dynamic> toMap(User value) {
///     return value.toMap();
///   }
/// }
///
/// ```

abstract class IDuModel {
  // ignore: public_member_api_docs
  IDuModel();

  late Meta _meta;
  late DuBox _box;

  bool get _isSettedMeta {
    try {
      _meta;
      return true;
    } catch (e) {
      return false;
    }
  }

  bool get _isSettedBox {
    try {
      _box;
      return true;
    } catch (e) {
      return false;
    }
  }

  /// The ID generated by the database.
  ///
  /// Returns `-1` if the metadata has not been set.
  int get generatedId => _isSettedMeta ? _meta.id : -1;

  /// Retrieves the content associated with this model.
  ///
  /// Supported readers:
  /// - `TextRawContentReader`
  /// - `TextCompressContentReader`
  ///
  /// ### Example
  /// ```dart
  /// final contentRes = await item.getContent<String>();
  /// if (contentRes.isErr) {
  ///   print('Content error: ${contentRes.unwrapError()}');
  ///   return;
  /// }
  /// print('Content: ${contentRes.unwrap()}');
  /// ```
  Future<Result<R, String>> getContent<R>() async {
    if (!_isSettedBox) {
      return Err('Box has not been set.');
    }

    return await _box.getContent<R>(this);
  }

  /// Deletes this model from the database.
  Future<Result<bool, String>> delete() async {
    if (!_isSettedBox) {
      return Err('Box has not been set.');
    }

    return await _box.deleteById(generatedId);
  }
}
